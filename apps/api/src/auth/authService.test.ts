// AuthService unit tests — Phase C identity port (Remote-verified behavior).
// Unit-level evidence with the REAL crypto stack (VeloraHasher + JwtService)
// and an in-memory UserStore (the authorized local persistence boundary).
import { test } from "node:test";
import assert from "node:assert/strict";
import { AuthService, AuthError, ACCESS_TOKEN_TTL_SECONDS } from "./authService.js";
import { MemoryUserStore } from "./memoryUserStore.js";
import { VeloraHasher } from "./hashing.js";
import { JwtService } from "./jwt.js";

const SECRET = "auth-service-unit-test-secret-0123456789abcdef"; // 42 chars, test-only
const PHP_BCRYPT_2Y_COST10 =
  "$2y$10$.vGA1O9wmRjrwAVXD98HNOgsNpDczlqm3Jq7KnEd1rVAGv3Fykk1a"; // PHP manual vector
const VECTOR_PASSWORD = "rasmuslerdorf"; // public documentation example, not a credential

interface TestHarness {
  store: MemoryUserStore;
  service: AuthService;
  /** Raw verification tokens generated by THIS service instance (in order). */
  tokens: string[];
}

let tokenCounter = 0;

function makeService(overrides: { now?: () => Date } = {}): TestHarness {
  const store = new MemoryUserStore();
  const tokens: string[] = [];
  const service = new AuthService({
    store,
    hasher: new VeloraHasher(),
    // JwtService clock is unix SECONDS; the service clock is a Date.
    jwt: JwtService.create(SECRET, {
      now: () => Math.floor((overrides.now ?? (() => new Date()))().getTime() / 1000),
    }),
    ...(overrides.now ? { now: overrides.now } : {}),
    // deterministic verification tokens (test injection; production uses CSPRNG)
    generateVerificationToken: () => {
      const t = `deterministic-verification-token-${++tokenCounter}-0123456789abcdef`;
      tokens.push(t);
      return t;
    },
  });
  return { store, service, tokens };
}

async function registerVerifiedUser(
  h: TestHarness,
  email = "user@velora.example",
  password = "a-strong-password-123",
): Promise<void> {
  await h.service.register({ email, password });
  const token = h.tokens.shift();
  assert.ok(token !== undefined, "verification token expected");
  await h.service.verifyEmail(token);
}

test("register: new user → {verificationRequired, email}, no messageKey", async () => {
  const h = makeService();
  const r = await h.service.register({ email: "new@velora.example", password: "a-strong-password-123" });
  assert.deepEqual(r, { verificationRequired: true, email: "new@velora.example" });
});

test("register: duplicate VERIFIED email → 409 EMAIL_ALREADY_REGISTERED", async () => {
  const h = makeService();
  await registerVerifiedUser(h, "dupe@velora.example");
  await assert.rejects(
    h.service.register({ email: "DUPE@velora.example", password: "another-strong-pass-456" }),
    (e: unknown) => e instanceof AuthError && e.status === 409 && e.code === "EMAIL_ALREADY_REGISTERED",
  );
});

test("register: unverified re-register → 60s retry delay, then resend path (reference semantics)", async () => {
  // NOTE (evidence-based Remote quirk, documented): the reference deletes prior
  // verification rows before creating a new one, so at most ONE row per user
  // exists when the 3-per-24h count runs — VERIFICATION_LIMIT is unreachable
  // in the reference and therefore also here (ported faithfully; flagged for
  // owner review when the Phase I email waves revisit resend limits).
  let clock = new Date("2026-09-12T10:00:00Z");
  const h = makeService({ now: () => clock });
  await h.service.register({ email: "unverified@velora.example", password: "a-strong-password-123" });

  clock = new Date("2026-09-12T10:00:30Z"); // within 60s → retry delay
  await assert.rejects(
    h.service.register({ email: "unverified@velora.example", password: "a-strong-password-123" }),
    (e: unknown) => e instanceof AuthError && e.code === "VERIFICATION_RETRY_DELAY",
  );

  clock = new Date("2026-09-12T10:02:00Z"); // after the interval → resend
  const r = await h.service.register({ email: "unverified@velora.example", password: "a-strong-password-123" });
  assert.equal(r.messageKey, "auth.verificationResent");
  assert.equal(r.verificationRequired, true);
});

test("verifyEmail: valid token verifies; replay → alreadyVerified; bad/expired → 401 INVALID_TOKEN", async () => {
  let clock = new Date("2026-09-12T10:00:00Z");
  const h = makeService({ now: () => clock });
  await h.service.register({ email: "verify@velora.example", password: "a-strong-password-123" });
  const token = h.tokens.shift();

  const first = await h.service.verifyEmail(token!);
  assert.equal(first.alreadyVerified, false);
  assert.equal(first.messageKey, "auth.emailVerified");

  const replay = await h.service.verifyEmail(token!);
  assert.equal(replay.alreadyVerified, true);
  assert.equal(replay.messageKey, "auth.emailAlreadyVerified");

  await assert.rejects(
    h.service.verifyEmail("not-a-real-token-0123456789abcdef"),
    (e: unknown) => e instanceof AuthError && e.status === 401 && e.code === "INVALID_TOKEN",
  );

  await h.service.register({ email: "expired@velora.example", password: "a-strong-password-123" });
  const expiredToken = h.tokens.shift();
  clock = new Date("2026-09-14T10:00:00Z"); // beyond the 24h expiry
  await assert.rejects(
    h.service.verifyEmail(expiredToken!),
    (e: unknown) => e instanceof AuthError && e.code === "INVALID_TOKEN",
  );
});

test("login: failure order — credentials, then status, then verification", async () => {
  const h = makeService();
  await registerVerifiedUser(h, "active@velora.example", "right-password-123");

  await assert.rejects(
    h.service.login({ email: "active@velora.example", password: "wrong-password-999" }),
    (e: unknown) => e instanceof AuthError && e.status === 401 && e.code === "INVALID_CREDENTIALS",
  );
  await assert.rejects(
    h.service.login({ email: "ghost@velora.example", password: "whatever-password-1" }),
    (e: unknown) => e instanceof AuthError && e.code === "INVALID_CREDENTIALS",
  );

  await registerVerifiedUser(h, "inactive@velora.example", "right-password-123");
  const inactive = await h.store.findUserByEmail("inactive@velora.example");
  assert.ok(inactive !== null);
  (inactive as { status: string }).status = "suspended";
  await assert.rejects(
    h.service.login({ email: "inactive@velora.example", password: "right-password-123" }),
    (e: unknown) => e instanceof AuthError && e.code === "ACCOUNT_INACTIVE",
  );
});

