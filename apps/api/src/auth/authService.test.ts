test("refresh: rotates the session; old token dies, new one works", async () => {
  const h = makeService();
  await registerVerifiedUser(h, "refresh@velora.example", "a-strong-password-123");
  const pair = await h.service.login({ email: "refresh@velora.example", password: "a-strong-password-123" });

  const rotated = await h.service.refresh(pair.refreshToken);
  assert.notEqual(rotated.refreshToken, pair.refreshToken);
  assert.notEqual(rotated.accessToken, pair.accessToken);

  await assert.rejects(
    h.service.refresh(pair.refreshToken),
    (e: unknown) => e instanceof AuthError && e.code === "INVALID_TOKEN",
  );
  const again = await h.service.refresh(rotated.refreshToken);
  assert.ok(again.refreshToken.length > 0);
});

test("refresh: expired session → SESSION_EXPIRED", async () => {
  let clock = new Date("2026-09-12T10:00:00Z");
  const h = makeService({ now: () => clock });
  await registerVerifiedUser(h, "exp@velora.example", "a-strong-password-123");
  const pair = await h.service.login({ email: "exp@velora.example", password: "a-strong-password-123" });
  clock = new Date("2026-11-01T10:00:00Z"); // > 30 days
  await assert.rejects(
    h.service.refresh(pair.refreshToken),
    (e: unknown) => e instanceof AuthError && e.code === "SESSION_EXPIRED",
  );
});

test("logout: revokes the session (idempotent); refresh after logout → INVALID_TOKEN", async () => {
  const h = makeService();
  await registerVerifiedUser(h, "out@velora.example", "a-strong-password-123");
  const pair = await h.service.login({ email: "out@velora.example", password: "a-strong-password-123" });
  await h.service.logout(pair.refreshToken);
  await h.service.logout(pair.refreshToken); // idempotent
  await assert.rejects(
    h.service.refresh(pair.refreshToken),
    (e: unknown) => e instanceof AuthError && e.code === "INVALID_TOKEN",
  );
});

