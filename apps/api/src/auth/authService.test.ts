test("login: legacy $2y$ verifies AND rehashes to exact Argon2id through the store (S5 boundary)", async () => {
  const h = makeService();
  const legacy = await h.store.createUser({
    email: "legacy@velora.example",
    passwordHash: PHP_BCRYPT_2Y_COST10,
    fullName: "Legacy User",
    timezone: "UTC",
    locale: "fa",
    now: new Date("2026-09-12T09:00:00Z"),
  });
  await h.store.markEmailVerified(legacy.id, new Date("2026-09-12T09:01:00Z"));

  const pair = await h.service.login({ email: "legacy@velora.example", password: VECTOR_PASSWORD });
  assert.equal(pair.tokenType, "Bearer");
  assert.equal(pair.expiresIn, ACCESS_TOKEN_TTL_SECONDS);
  assert.equal(pair.user.email, "legacy@velora.example");
  assert.equal(pair.user.plan, "free");

  const stored = await h.store.findUserByEmail("legacy@velora.example");
  assert.ok(stored!.passwordHash.startsWith("$argon2id$v=19$m=19456,t=2,p=1$"), "rehash persisted");

  const payload = h.service.verifyAccessToken(pair.accessToken);
  assert.equal(payload?.sub, legacy.id);
  assert.equal(payload?.role, "user");

  const second = await h.service.login({ email: "legacy@velora.example", password: VECTOR_PASSWORD });
  assert.ok(second.accessToken.length > 0);
  const storedAfter = await h.store.findUserByEmail("legacy@velora.example");
  assert.equal(storedAfter!.passwordHash, stored!.passwordHash, "no unnecessary rehash");
});

